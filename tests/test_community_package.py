"""Contribution lint and the community package composer.

Composing needs only the standard library. The lint reads rules through the
pinned Telltale, so its tests run when TELLTALE_BIN names a pinned build, as in
`scripts/linux-check.sh`.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import community_package  # noqa: E402
from community_package import ContentError, Rule  # noqa: E402


RULE = """title: Synthetic {name}
id: {uuid}
name: {name}
taxonomy: telltale
status: {status}
logsource:
    product: ai_agent
    category: tool_activity
detection:
    selection:
        - tool.command|re|i: &pattern '{pattern}'
        - tool.arguments|re|i: *pattern
    condition: selection
level: low
telltale:
    category: execution
    score: 10
    explanation: Synthetic marker in an agent tool request.
"""


def write_rule(directory: Path, name: str, status: str, uuid: str, pattern: str) -> Rule:
    path = directory / (name.replace(".", "_") + ".yml")
    path.write_text(RULE.format(name=name, status=status, uuid=uuid, pattern=pattern), encoding="utf-8")
    return Rule(name, status, path, {})


class ComposePackageTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        (self.root / "rules").mkdir()
        shutil.copyfile(ROOT / "community-package.json", self.root / "community-package.json")

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def rule(self, name: str, status: str, uuid: str, pattern: str = "MARKER") -> Rule:
        return write_rule(self.root / "rules", name, status, uuid, pattern)

    def test_released_package_ships_test_and_stable_rules_sorted_by_name(self) -> None:
        rules = [
            self.rule("tdx.a_b.c", "stable", "00000000-0000-4000-8000-000000000001"),
            self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002"),
            self.rule("tdx.a.draft", "experimental", "00000000-0000-4000-8000-000000000003"),
        ]
        package = community_package.compose_package(self.root, rules, "0.1.0", "0" * 40)
        self.assertEqual(package.splitlines()[:11], [
            "# Generated by telltale-detections scripts/community_package.py. Do not edit.",
            "format: telltale-rule-package/v2",
            'id: "telltale.community"',
            'title: "Telltale community detections"',
            'version: "0.1.0"',
            'publisher: "Telltale community detections"',
            'license: "Apache-2.0"',
            'rule_namespace: "tdx"',
            'source: "https://github.com/Dark-Roast-Cyber/telltale-detections"',
            'revision: "0000000000000000000000000000000000000000"',
            "---",
        ])
        # `.` sorts before `_`, so name order differs from file-name order here.
        names = [line for line in package.splitlines() if line.startswith("name: ")]
        self.assertEqual(names, ["name: tdx.a.z", "name: tdx.a_b.c"])

    def test_candidate_package_ships_every_maturity(self) -> None:
        rules = [
            self.rule("tdx.a.draft", "experimental", "00000000-0000-4000-8000-000000000003"),
            self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002"),
        ]
        package = community_package.compose_package(
            self.root, rules, "0.0.0-candidate", None, community_package.MATURITIES
        )
        self.assertIn("\nname: tdx.a.draft\n", package)
        self.assertIn("\nname: tdx.a.z\n", package)
        self.assertNotIn("revision:", package)

    def test_a_package_of_only_experimental_rules_is_refused(self) -> None:
        rules = [self.rule("tdx.a.draft", "experimental", "00000000-0000-4000-8000-000000000003")]
        with self.assertRaises(ContentError):
            community_package.compose_package(self.root, rules, "0.1.0", None)

    def test_each_rule_file_follows_the_header_as_its_own_document(self) -> None:
        rules = [self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002", "ZED")]
        package = community_package.compose_package(self.root, rules, "0.1.0", None)
        self.assertTrue(package.endswith(
            'source: "https://github.com/Dark-Roast-Cyber/telltale-detections"\n'
            "---\n"
            "# rules/tdx_a_z.yml\n"
            "title: Synthetic tdx.a.z\n"
            "id: 00000000-0000-4000-8000-000000000002\n"
            "name: tdx.a.z\n"
            "taxonomy: telltale\n"
            "status: test\n"
            "logsource:\n"
            "    product: ai_agent\n"
            "    category: tool_activity\n"
            "detection:\n"
            "    selection:\n"
            "        - tool.command|re|i: &pattern 'ZED'\n"
            "        - tool.arguments|re|i: *pattern\n"
            "    condition: selection\n"
            "level: low\n"
            "telltale:\n"
            "    category: execution\n"
            "    score: 10\n"
            "    explanation: Synthetic marker in an agent tool request.\n"
        ))

    def test_crlf_rule_files_compose_to_lf_package_text(self) -> None:
        rule = self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002")
        rule.path.write_bytes(rule.path.read_bytes().replace(b"\n", b"\r\n"))
        package = community_package.compose_package(self.root, [rule], "0.1.0", None)
        self.assertNotIn("\r", package)

    def test_rule_files_with_document_markers_are_refused(self) -> None:
        rule = self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002")
        rule.path.write_text("---\n" + rule.path.read_text(encoding="utf-8"), encoding="utf-8")
        with self.assertRaises(ContentError) as caught:
            community_package.compose_package(self.root, [rule], "0.1.0", None)
        self.assertIn("without YAML markers", str(caught.exception))

    def test_revision_must_be_a_full_commit_sha(self) -> None:
        rules = [self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002")]
        with self.assertRaises(ContentError):
            community_package.compose_package(self.root, rules, "0.1.0", "not-a-sha")

    def test_hidden_characters_in_rule_files_are_refused(self) -> None:
        rule = self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002", "MARK‮ER")
        with self.assertRaises(ContentError) as caught:
            community_package.compose_package(self.root, [rule], "0.1.0", None)
        self.assertIn("forbidden character U+202E", str(caught.exception))

    def test_write_package_writes_the_package_and_its_checksum(self) -> None:
        rules = [self.rule("tdx.a.z", "test", "00000000-0000-4000-8000-000000000002")]
        out = self.root / "dist"
        path = community_package.write_package(self.root, rules, "0.1.0", None, out)
        self.assertEqual(path.name, "telltale.community-0.1.0.package.yaml")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        self.assertEqual((out / "SHA256SUMS").read_text(encoding="utf-8"), f"{digest}  {path.name}\n")

    def test_rules_directory_holds_only_yml_files(self) -> None:
        (self.root / "rules" / "draft.yaml").write_text("title: x\n", encoding="utf-8")
        with self.assertRaises(ContentError) as caught:
            community_package.rule_paths(self.root)
        self.assertIn("rules/draft.yaml", str(caught.exception))

    def test_lint_requires_the_pinned_telltale_revision(self) -> None:
        shutil.copyfile(ROOT / "pins.json", self.root / "pins.json")
        binary = self.root / "telltale"
        binary.write_text("#!/bin/sh\necho 'telltale 0.0.0 (0123456789ab)'\n", encoding="utf-8")
        binary.chmod(0o755)
        with self.assertRaises(ContentError) as caught:
            community_package.lint(self.root, binary)
        self.assertIn("must report revision", str(caught.exception))


@unittest.skipUnless(os.environ.get("TELLTALE_BIN"), "set TELLTALE_BIN to a pinned Telltale build")
class LintTests(unittest.TestCase):
    """The lint's policy checks over what the pinned Telltale reads."""

    def setUp(self) -> None:
        self.telltale = Path(os.environ["TELLTALE_BIN"])
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name) / "content"
        for name in ("rules", "scenarios", "docs"):
            shutil.copytree(ROOT / name, self.root / name)
        for name in ("community-package.json", "pins.json"):
            shutil.copyfile(ROOT / name, self.root / name)
        self.rule = self.root / "rules" / "tdx_persistence_mcp_server_registration.yml"

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def assert_lint_error(self, fragment: str) -> None:
        with self.assertRaises(ContentError) as caught:
            community_package.lint(self.root, self.telltale)
        self.assertIn(fragment, str(caught.exception))

    def edit_rule(self, old: str, new: str) -> None:
        text = self.rule.read_text(encoding="utf-8")
        self.assertIn(old, text)
        self.rule.write_text(text.replace(old, new, 1), encoding="utf-8")

    def test_repository_rules_pass_lint_and_load_from_the_package(self) -> None:
        rules = community_package.lint(ROOT, self.telltale)
        self.assertEqual([(rule.name, rule.status) for rule in rules], [
            ("tdx.persistence.git_hook_change", "test"),
            ("tdx.persistence.mcp_server_registration", "test"),
            ("tdx.persistence.powershell_profile_write", "test"),
            ("tdx.persistence.windows_agent_command", "test"),
            ("tdx.persistence.windows_service_change", "test"),
            ("tdx.persistence.wmi_event_subscription", "test"),
            ("tdx.privilege_escalation.container_host_escape", "experimental"),
            ("tdx.privilege_escalation.container_privileged_launch", "experimental"),
        ])
        self.assertTrue(community_package.validate(ROOT, self.telltale).startswith("telltale "))

    def test_names_must_use_the_package_namespace(self) -> None:
        self.edit_rule("name: tdx.persistence.mcp_server_registration", "name: mcp.server_registration")
        self.assert_lint_error("must start with `tdx.`")

    def test_file_name_must_follow_the_rule_name(self) -> None:
        self.rule.rename(self.root / "rules" / "tdx_persistence_mcp.yml")
        self.assert_lint_error("is rules/tdx_persistence_mcp_server_registration.yml")

    def test_status_must_be_a_maturity(self) -> None:
        self.edit_rule("status: test", "status: deprecated")
        self.assert_lint_error("`status` must be one of experimental, test, stable")

    def test_description_is_required(self) -> None:
        text = self.rule.read_text(encoding="utf-8")
        start = text.index("description: ")
        self.rule.write_text(text[:start] + text[text.index("\n", start) + 1:], encoding="utf-8")
        self.assert_lint_error("`description` is required")

    def test_date_is_required(self) -> None:
        self.edit_rule("date: 2026-10-13\n", "")
        self.assert_lint_error("`date` is required")

    def test_rules_reference_their_analyst_note(self) -> None:
        self.edit_rule(
            "    - https://github.com/Dark-Roast-Cyber/telltale-detections/blob/main/docs/detections/"
            "tdx.persistence.mcp_server_registration.md",
            "    - https://example.com/mcp",
        )
        self.assert_lint_error("`references` must include")

    def test_rules_need_an_analyst_note(self) -> None:
        (self.root / "docs" / "detections" / "tdx.persistence.mcp_server_registration.md").unlink()
        self.assert_lint_error("needs docs/detections/tdx.persistence.mcp_server_registration.md")

    def test_rules_need_a_benign_scenario(self) -> None:
        for name in ("mcp_server_list.json", "mcp_add_json_help.json", "mcp_add_help.json"):
            (self.root / "scenarios" / "benign" / name).rename(
                self.root / "scenarios" / "visibility-limited" / name
            )
        self.assert_lint_error("`tdx.persistence.mcp_server_registration` needs a benign scenario")

    def test_a_rule_file_holds_one_rule(self) -> None:
        text = self.rule.read_text(encoding="utf-8")
        second = (text.replace("tdx.persistence.mcp_server_registration", "tdx.persistence.mcp_second")
                  .replace("id: 51dcf092-f84d-4c8a-9e62-6721494bb644", "id: 9b0a2f3e-6a43-4c39-8a43-7c4b1c1d2e3f"))
        self.rule.write_text(text + "---\n" + second, encoding="utf-8")
        self.assert_lint_error("a rule file holds exactly one rule")

    def test_ids_are_unique_across_files(self) -> None:
        self.edit_rule("id: 51dcf092-f84d-4c8a-9e62-6721494bb644", "id: df8e8e98-fdc2-4a5b-af57-9d170c0b3f2e")
        self.assert_lint_error("is also the id of `tdx.persistence.git_hook_change`")

    def test_display_text_has_no_markup(self) -> None:
        self.edit_rule("    explanation: 'An agent", "    explanation: 'An <b>agent</b>")
        self.assert_lint_error("`explanation` must not contain markup or links")

    def test_telltale_notices_fail_the_lint(self) -> None:
        # A case-insensitive selection with a case-sensitive filter loads with
        # Telltale's `filter_case_mismatch` notice.
        text = self.rule.read_text(encoding="utf-8")
        start, end = text.index("detection:\n"), text.index("falsepositives:\n")
        self.rule.write_text(text[:start] + (
            "detection:\n"
            "    selection:\n"
            "        tool.command|re|i: 'mcp add'\n"
            "    filter:\n"
            "        tool.command|contains|cased: 'mcp add --help'\n"
            "    condition: selection and not filter\n"
        ) + text[end:], encoding="utf-8")
        self.assert_lint_error("filter_case_mismatch")

    def test_telltale_rejects_escaped_hidden_characters(self) -> None:
        self.edit_rule("    category: persistence", '    category: "persistence\\u202E"')
        self.assert_lint_error("Telltale rejected it")


if __name__ == "__main__":
    unittest.main()
